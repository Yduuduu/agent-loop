def build_pdf(output_path: Path, title: str, sections: list[tuple[str, list[str]]]) -> None:
    output_path.parent.mkdir(parents=True, exist_ok=True)

    c = canvas.Canvas(str(output_path), pagesize=A4)
    width, height = A4
    margin = 20 * mm
    y = height - margin

    c.setFont(FONT_NAME, 16)
    c.drawString(margin, y, title)
    y -= 12 * mm

    for heading, paragraphs in sections:
        if y < margin + 30 * mm:
            c.showPage()
            y = height - margin

        c.setFont(FONT_NAME, 13)
        c.drawString(margin, y, heading)
        y -= 8 * mm

        c.setFont(FONT_NAME, 10.5)
        for paragraph in paragraphs:
            for line in _wrap(paragraph, max_chars=44):
                if y < margin:
                    c.showPage()
                    c.setFont(FONT_NAME, 10.5)
                    y = height - margin
                c.drawString(margin, y, line)
                y -= 6.5 * mm
            y -= 2 * mm

        y -= 6 * mm

    c.save()
    print(f"wrote {output_path}")


def build_all() -> None:
    pdfmetrics.registerFont(UnicodeCIDFont(FONT_NAME))
    build_pdf(OUTPUT_DIR / "refund_policy.pdf", TITLE, REFUND_POLICY_SECTIONS)
    for filename, _product_category, title, sections in EDU_POLICY_DOCUMENTS:
        build_pdf(OUTPUT_DIR / filename, title, sections)


def _wrap(text: str, max_chars: int) -> list[str]:
    lines: list[str] = []
    current = ""
    for ch in text:
        current += ch
        if len(current) >= max_chars:
            lines.append(current)
            current = ""
    if current:
        lines.append(current)
    return lines


if __name__ == "__main__":
    build_all()
